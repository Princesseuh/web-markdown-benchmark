// Install footprint per benchmarked library: transitive dependency count and
// total on-disk size of all package files in the dependency closure. Walks the
// resolved pnpm tree under node_modules, so numbers reflect what this repo's
// lockfile actually installs.
//
// Sizes are machine-independent (lockfile-determined), so unlike the timing
// report this writes one shared table outside the per-environment sections.
import { readdirSync, readFileSync, realpathSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const readmeUrl = new URL("../README.md", import.meta.url);

// Each entry lists the packages you need to import to render markdown → HTML
// with no extensions (no GFM, no frontmatter, no plugins).
const benchmarkedPackages: { name: string; roots: string[] }[] = [
  { name: "satteri", roots: ["satteri"] },
  { name: "remark", roots: ["unified", "remark-parse", "remark-rehype", "rehype-stringify"] },
  { name: "markdown-it", roots: ["markdown-it"] },
  { name: "markdown-exit", roots: ["markdown-exit"] },
  { name: "marked", roots: ["marked"] },
  { name: "comark", roots: ["comark"] },
  { name: "@mdx-js/mdx", roots: ["@mdx-js/mdx"] },
];

const START = "<!-- deps:start -->";
const END = "<!-- deps:end -->";

// Real files only. Symlinks are how pnpm wires sibling dependencies together;
// those packages are visited separately by the BFS in `analyze`.
function dirSize(dir: string): number {
  let bytes = 0;
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.isSymbolicLink()) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) bytes += dirSize(full);
    else if (entry.isFile()) bytes += statSync(full).size;
  }
  return bytes;
}

// Scope dirs (`@foo`) are descended one level so returned names are full package specifiers.
function listSiblings(nodeModulesDir: string, selfName: string): string[] {
  const out: string[] = [];
  const selfIsScoped = selfName.startsWith("@");
  for (const entry of readdirSync(nodeModulesDir, { withFileTypes: true })) {
    const name = entry.name;
    if (name.startsWith(".")) continue;
    if (!selfIsScoped && name === selfName) continue;
    if (name.startsWith("@")) {
      for (const sub of readdirSync(join(nodeModulesDir, name), { withFileTypes: true })) {
        const full = `${name}/${sub.name}`;
        if (full !== selfName) out.push(full);
      }
    } else {
      out.push(name);
    }
  }
  return out;
}

interface Stats {
  transitive: number;
  bytes: number;
}

function analyze(roots: string[]): Stats {
  const seen = new Set<string>();
  const queue: string[] = roots.map((name) => realpathSync(join(repoRoot, "node_modules", name)));
  let bytes = 0;
  while (queue.length > 0) {
    const pkgPath = queue.shift()!;
    if (seen.has(pkgPath)) continue;
    seen.add(pkgPath);
    bytes += dirSize(pkgPath);
    const manifest = JSON.parse(readFileSync(join(pkgPath, "package.json"), "utf-8"));
    const pkgName: string = manifest.name;
    const nmDir = pkgName.startsWith("@") ? dirname(dirname(pkgPath)) : dirname(pkgPath);
    for (const sib of listSiblings(nmDir, pkgName)) {
      const sibPath = realpathSync(join(nmDir, sib));
      if (!seen.has(sibPath)) queue.push(sibPath);
    }
  }
  return { transitive: seen.size - roots.length, bytes };
}

function fmtSize(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${Math.round(bytes / 1024)} KB`;
  return `${(bytes / 1024 / 1024).toFixed(2)} MB`;
}

const rows = benchmarkedPackages
  .map(({ name, roots }) => ({ name, ...analyze(roots) }))
  .sort((a, b) => a.bytes - b.bytes);

type Align = "l" | "r";
function table(headers: string[], align: Align[], cells: string[][]): string {
  const width = headers.map((h, i) => Math.max(h.length, ...cells.map((row) => row[i].length)));
  const pad = (text: string, i: number) =>
    align[i] === "r" ? text.padStart(width[i]) : text.padEnd(width[i]);
  const line = (row: string[]) => `| ${row.map(pad).join(" | ")} |`;
  const sep = `| ${width
    .map((w, i) => (align[i] === "r" ? `${"-".repeat(w - 1)}:` : "-".repeat(w)))
    .join(" | ")} |`;
  return [line(headers), sep, ...cells.map(line)].join("\n");
}

const tableText = table(
  ["Parser", "deps", "install size"],
  ["l", "r", "r"],
  rows.map((row) => [`\`${row.name}\``, String(row.transitive), fmtSize(row.bytes)]),
);

const section = `${START}

## Install footprint

<!-- Generated by \`nr bench:deps\`. Do not edit this section by hand. -->

Transitive dependency count and total on-disk size of each library's basic markdown → HTML pipeline, with no other extensions installed. \`deps\` counts packages pulled in beyond the libraries themselves; \`install size\` sums every file in the closure. For both stats, lower is better.

${tableText}

**Note:** Certain libraries inherently require multiple packages to provide Markdown to HTML.

**Note 2:** For libraries with native binaries, the install size depends on the platform. Linux binaries (what is being measured here) tends to be on the larger side.

${END}`;

const readme = readFileSync(readmeUrl, "utf-8");
const startAt = readme.indexOf(START);
if (startAt === -1) {
  writeFileSync(readmeUrl, `${readme.replace(/\s+$/, "")}\n\n${section}\n`);
} else {
  const endAt = readme.indexOf(END, startAt);
  if (endAt === -1) throw new Error(`README has ${START} without ${END}`);
  writeFileSync(
    readmeUrl,
    `${readme.slice(0, startAt)}${section}${readme.slice(endAt + END.length)}`,
  );
}

console.error(`Wrote install footprint for ${rows.length} package(s) to README.md`);
